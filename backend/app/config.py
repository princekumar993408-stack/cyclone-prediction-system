from pathlib import Path
from pydantic import BaseModel

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "app" / "data"

class Settings(BaseModel):
    app_name: str = "Cyclone Prediction Intelligence Platform"
    app_version: str = "2.0.0"
    api_prefix: str = "/api"
    data_dir: Path = DATA_DIR
    
    # Meteorological Standards (IMD - India Meteorological Department)
    basin_name: str = "North Indian Ocean (Bay of Bengal & Arabian Sea)"
    environment_pressure_mb: float = 1010.0  # Standard peripheral pressure
    
    # Official Disclaimer
    academic_disclaimer: str = (
        "ACADEMIC RESEARCH NOTICE: All storm trajectory forecasts, intensity estimates, and "
        "cyclone detections are generated by experimental machine learning algorithms for academic "
        "and scientific research purposes only. This platform does NOT provide official meteorological warnings. "
        "Always consult the India Meteorological Department (IMD) or relevant national meteorological agencies "
        "for life-safety, disaster preparedness, and official evacuation advisories."
    )

settings = Settings()
